// ---------------------------------------------------------------- 尾巴（一像素细的镰刀尾：从尾根往后下方垂、梢往上一勾）

const TAIL: Record<string, [number, number][]> = {
  down: [[8, 9], [7, 10], [6, 11], [5, 12], [4, 12], [3, 11]],
  wag: [[8, 9], [7, 10], [6, 10], [5, 11], [4, 11], [3, 10]],
  // 跑起来拉直往后，梢微微上翘
  run: [[8, 8], [7, 8], [6, 8], [5, 8], [4, 8], [3, 7]],
  runUp: [[8, 8], [7, 7], [6, 7], [5, 7], [4, 6], [3, 6]],
};

/** 拼一帧：身子和头随 dy 浮动（腿是贴地画的，不动），尾巴跟着身子；一起描边。 */
function frame(head: string, legs: string, tail: string, dy = 0): Grid {
  const px: string[][] = Array.from({ length: HOUND_H }, () => Array(HOUND_W).fill('.'));
  const put = (p: Part, oy: number) =>
    p.rows.forEach((r, j) =>
      [...r].forEach((ch, x) => {
        const y = p.y + oy + j;
        if (ch !== '.' && y >= 0 && y < HOUND_H) px[y][x] = ch;
      }),
    );
  TAIL[tail].forEach(([x, y], i, a) => {
    const Y = y + dy;
    if (Y >= 0 && Y < HOUND_H) px[Y][x] = i >= a.length - 2 ? 'O' : 'K';
  });
  put(LEGS[legs], 0);
  put(BODY, dy);
  put(HEAD[head], dy);
  return outline(compose(HOUND_W, HOUND_H, [{ g: grid(px.map((r) => r.join(''))), x: 0, y: 0 }]), 'k', SEL);
}

export type HoundPose = 'idle' | 'trot' | 'run' | 'bite';

export function makeHoundFrames(): Record<HoundPose, Grid[]> {
  return {
    idle: [frame('stand', 'stand', 'down'), frame('stand', 'stand', 'wag'), frame('sniff', 'stand', 'down'), frame('look', 'stand', 'wag')],
    trot: [frame('stand', 'trotA', 'wag', 0), frame('stand', 'trotB', 'down', 0), frame('stand', 'trotC', 'wag', 0), frame('stand', 'trotD', 'down', 0)],
    run: [frame('run', 'runA', 'run', 1), frame('run', 'runB', 'run', 0), frame('run', 'runC', 'runUp', -1), frame('run', 'runD', 'run', 0)],
    bite: [frame('bite', 'bite', 'run', 1), frame('shut', 'bite', 'run', 1)],
  };
}

export const HOUND_FRAMES = makeHoundFrames();
